/**
 * Regenerates src/data/crawlerSnapshots.ts: the visible text of each static page, taken from the running site, so the
 * server-sent HTML carries the same copy visitors read. Run after editing page copy:
 *   npm run build && node scripts/snapshot-crawler-text.mjs [baseUrl]   (baseUrl defaults to http://localhost:5197)
 * Needs Playwright with a Chromium (PLAYWRIGHT_BROWSERS_PATH or executablePath via CHROMIUM_PATH).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const base = process.argv[2] || 'http://localhost:5197';
const routes = ['/about', '/services', '/industries', '/contact', '/ecosystem'];
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/data/crawlerSnapshots.ts');

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const snapshots = {};
for (const route of routes) {
  const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
  await page.goto(base + route, { waitUntil: 'load' });
  await page.waitForTimeout(3000);
  // Walk the page so lazy sections mount, then read the text of every heading/paragraph/list item outside header, footer and nav.
  const height = await page.evaluate(() => document.body.scrollHeight);
  for (let y = 0; y < height; y += 700) {
    await page.evaluate((v) => window.scrollTo(0, v), y);
    await page.waitForTimeout(120);
  }
  await page.waitForTimeout(800);
  const collect = () =>
    page.evaluate(() => {
      const blocks = [];
      document.querySelectorAll('h1, h2, h3, p, li').forEach((el) => {
        if (el.closest('header, footer, nav, button, form, [role="dialog"], [data-ssr-content]')) return;
        const text = (el.textContent || '').replace(/\s+/g, ' ').trim();
        if (text.length >= 3) blocks.push({ tag: el.tagName.toLowerCase(), text });
      });
      return blocks;
    });

  let blocks = await collect();
  // The industries page shows one sector at a time behind a picker: click through every sector so each one's copy is captured.
  if (route === '/industries') {
    const pickers = page.locator('[data-section="industries"] button').filter({ hasNotText: /build|blueprint|solution|request/i });
    const count = await pickers.count();
    for (let i = 0; i < count; i++) {
      await pickers.nth(i).click().catch(() => {});
      await page.waitForTimeout(400);
      blocks = blocks.concat(await collect());
    }
  }

  // De-duplicate, and drop list items that are just a card's heading + paragraph glued together (the same text is captured
  // separately as a heading and a paragraph).
  const seen = new Set();
  blocks = blocks.filter((b) => (seen.has(b.text) ? false : (seen.add(b.text), true)));
  const texts = blocks.map((b) => b.text);
  blocks = blocks.filter((b) => !(b.tag === 'li' && texts.some((t) => t !== b.text && t.length >= 12 && b.text.includes(t))));
  snapshots[route] = blocks;
  console.log(route, snapshots[route].length, 'blocks');
}
await browser.close();
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Generated by scripts/snapshot-crawler-text.mjs - the visible text of each static page. Do not edit by hand.\nexport const CRAWLER_SNAPSHOTS: Record<string, { tag: string; text: string }[]> = ${JSON.stringify(snapshots, null, 1)};\n`
);
